                FeatureCard(
                    icon = Icons.Default.Security,
                    title = "100% Account Isolation",
                    description = "Strict local data separation ensures your laundry records remain strictly private."
                )
            }
        }

        Spacer(modifier = Modifier.height(32.dp))

